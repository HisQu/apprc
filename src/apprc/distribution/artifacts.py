"""Explicit generated output publication and zero-write drift checking."""

import os
from collections.abc import Sequence

from apprc.distribution.models import Artifact
from apprc.user_files.app_home.locations import (
    assert_no_links,
    write_bytes_atomic,
)


def write_artifacts(
    artifacts: Sequence[Artifact], *, check: bool = False
) -> None:
    """Write owned outputs or report all missing/drifted artifacts without writes.

    :param artifacts: Generated bytes and explicit repository-relative destinations.
    :param check: Inspect bytes/executable flags only; never mkdir/chmod/replace.
    """
    destinations = [
        artifact.project_root.resolve() / artifact.destination
        for artifact in artifacts
    ]
    if len(set(destinations)) != len(destinations):
        raise ValueError("Duplicate generated artifact destinations.")
    drifted: list[str] = []
    for artifact, destination in zip(artifacts, destinations, strict=True):
        assert_no_links(destination)
        try:
            current = destination.read_bytes()
        except FileNotFoundError:
            current = None
        mode_matches = destination.exists() and (
            os.name == "nt"
            or bool(destination.stat().st_mode & 0o111) == artifact.executable
        )
        if current == artifact.content and mode_matches:
            continue
        if check:
            drifted.append(str(artifact.destination))
            continue
        if current != artifact.content:
            write_bytes_atomic(destination, artifact.content)
        if os.name != "nt":
            destination.chmod(0o755 if artifact.executable else 0o644)
    if drifted:
        raise ValueError(
            "Generated artifacts are missing or drifted; run just make-artifacts:\n"
            + "\n".join(f"- {destination}" for destination in drifted)
        )
