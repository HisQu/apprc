"""Strict external templates and a shared deterministic standalone loader."""

from __future__ import annotations

import base64
import io
import json
import shlex
import urllib.parse
from importlib.resources import files
from pathlib import PurePosixPath
from typing import TYPE_CHECKING
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

from apprc.distribution.models import Artifact, DistributionSpec, PayloadTree
from apprc.distribution.standalone import (
    MANAGEMENT_REQUIREMENTS,
    payload_archive,
)

if TYPE_CHECKING:
    from jinja2 import Environment


def _environment() -> Environment:
    from jinja2 import Environment, PackageLoader, StrictUndefined

    environment = Environment(
        loader=PackageLoader("apprc.distribution", "templates"),
        undefined=StrictUndefined,
        autoescape=False,
        keep_trailing_newline=True,
    )
    environment.filters.update(
        json=lambda value: json.dumps(value, ensure_ascii=True),
        sh=shlex.quote,
        ps=lambda value: "'" + value.replace("'", "''") + "'",
        cmd=lambda value: (
            '"' + value.replace("%", "%%").replace('"', '""') + '"'
        ),
    )
    return environment


def standalone_script(
    spec: DistributionSpec,
    payload: PayloadTree,
    *,
    entry: str,
    public_entry: bool = True,
) -> bytes:
    """Render the small loader around the same explicit ordinary-module tree.

    Application runtime constraints remain in the bundled source contract;
    they must not constrain the independent management-loader environment.

    :param spec: Portable author inputs.
    :param payload: Explicit module/resource inclusion tree.
    :param entry: Selected bundled entry module.
    :param public_entry: Validate the public release asset rather than saved support.
    :return: UTF-8 PEP 723 executable script bytes.
    """
    archive = base64.b64encode(payload_archive(spec, payload)).decode("ascii")
    release_contract = None
    if (
        public_entry
        and entry == payload.entry_module
        and spec.source_mode == "release"
    ):
        source_path = urllib.parse.urlsplit(spec.release_asset or "").path
        release_contract = {
            "app_id": spec.metadata.identity.app_id,
            "distribution": spec.metadata.identity.distribution,
            "version": spec.release_version,
            "commit": spec.release_commit,
            "payload_format": spec.payload_format,
            "payload_filename": f"main-installer.{'pyz' if spec.payload_format == 'zipapp' else 'py'}",
            "package_filename": PurePosixPath(
                source_path or spec.release_asset or ""
            ).name,
            "package_digest": spec.release_digest,
        }
    return (
        _environment()
        .get_template("payload.py.jinja")
        .render(
            archive=archive,
            entry=entry,
            requirements=MANAGEMENT_REQUIREMENTS,
            release_contract=release_contract,
        )
        .encode("utf-8")
    )


def _artifact(
    spec: DistributionSpec,
    address: str,
    content: bytes,
    *,
    executable: bool = False,
) -> Artifact:
    """Place generated bytes under the author's explicit repository root."""
    from pathlib import PurePosixPath

    return Artifact(
        PurePosixPath(address), content, executable, spec.metadata.project_root
    )


def _shell_double_quoted(value: str) -> str:
    """Escape shell expansions within a double-quoted generated path."""
    return value.replace("$", "\\$").replace("`", "\\`").replace('"', '\\"')


def render_bootstraps(spec: DistributionSpec) -> tuple[Artifact, ...]:
    """Render native checkout or standalone-source bootstraps."""
    environment = _environment()
    base = f"{spec.metadata.distribution_path}/artifacts/installer"
    release_fetcher = ""
    main_fetcher = ""
    repository_url = ""
    if spec.repository_url is not None:
        repository = urllib.parse.urlsplit(spec.repository_url)
        repository_parts = [part for part in repository.path.split("/") if part]
        if (
            repository.scheme != "https"
            or repository.hostname != "github.com"
            or repository.username is not None
            or repository.password is not None
            or repository.query
            or repository.fragment
            or len(repository_parts) != 2
        ):
            raise ValueError(
                "Remote source bootstrap requires a credential-free GitHub repository URL."
            )
        repository_url = (
            f"https://github.com/{repository_parts[0]}/"
            f"{repository_parts[1].removesuffix('.git')}"
        )
        release_fetcher = environment.get_template(
            "release_fetcher.py.jinja"
        ).render(
            app_id=spec.metadata.identity.app_id,
            distribution=spec.metadata.identity.distribution,
            repository_url=repository_url,
            release_version=spec.release_version or "latest",
        )
        installer = (
            PurePosixPath(spec.metadata.distribution_path)
            / "artifacts"
            / "installer"
        )
        main_fetcher = environment.get_template("main_fetcher.py.jinja").render(
            repository_url=repository_url,
            installer_path=str(
                installer
                / (
                    "main-installer.pyz"
                    if spec.payload_format == "zipapp"
                    else "main-installer.py"
                )
            ),
            payload_format=spec.payload_format,
        )
    if spec.source_mode in {"release", "main"} and not repository_url:
        raise ValueError(
            "Remote source bootstrap requires a GitHub repository URL."
        )
    template_values = {
        "zipapp": spec.payload_format == "zipapp",
        "source_mode": spec.source_mode,
        "repository_url": repository_url,
        "release_fetcher": release_fetcher,
        "main_fetcher": main_fetcher,
        "has_repository": bool(repository_url),
    }
    shell = (
        environment.get_template("bootstrap.sh.jinja")
        .render(**template_values)
        .encode()
    )
    powershell = (
        environment.get_template("bootstrap.ps1.jinja")
        .render(**template_values)
        .encode()
    )
    bootstrap = (
        _artifact(spec, f"{base}/bootstrap.sh", shell, executable=True),
        _artifact(spec, f"{base}/bootstrap.ps1", powershell),
    )
    requirements: tuple[Artifact, ...] = ()
    if spec.payload_format == "zipapp":
        requirements = (
            _artifact(
                spec,
                f"{base}/main-installer-requirements.txt",
                ("\n".join(MANAGEMENT_REQUIREMENTS) + "\n").encode(),
            ),
        )
    if spec.source_mode in {"release", "main"}:
        app_shell = shell
        app_cmd = (
            environment.get_template("bootstrap.cmd.jinja")
            .render(
                powershell_b64=base64.b64encode(powershell).decode("ascii"),
            )
            .encode("ascii")
        )
        release_bootstrap = (_artifact(spec, "bootstrap.ps1", powershell),)
    else:
        windows_path = spec.metadata.distribution_path.as_posix().replace(
            "%", "%%"
        )
        app_shell = (
            f'#!/bin/sh\nset -eu\nHERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
            f'exec "$HERE/{_shell_double_quoted(spec.metadata.distribution_path.as_posix())}'
            '/artifacts/installer/bootstrap.sh" "$@"\n'
        ).encode()
        app_cmd = (
            '@echo off\r\nsetlocal\r\nset "HERE=%~dp0"\r\n'
            "powershell.exe -NoProfile -ExecutionPolicy Bypass -File "
            f'"%HERE%{windows_path}\\artifacts\\installer\\bootstrap.ps1" %*\r\n'
            "exit /b %ERRORLEVEL%\r\n"
        ).encode()
        release_bootstrap = ()
    return (
        *bootstrap,
        *requirements,
        *release_bootstrap,
        _artifact(spec, "app-install.sh", app_shell, executable=True),
        _artifact(spec, "app-install.cmd", app_cmd),
    )


def _wrappers(
    spec: DistributionSpec, *, command: str, entry: str
) -> tuple[Artifact, ...]:
    """Generate native root wrappers that dispatch to the fixed saved installation."""
    app_id = spec.metadata.identity.app_id
    saved = "launch.sh" if entry == "launch" else "uninstall.sh"
    batch_saved = "launch.cmd" if entry == "launch" else "uninstall.cmd"
    shell = (
        "#!/bin/sh\nset -eu\n"
        "HOME=${HOME:?HOME is required to locate the installation}\n"
        'case "$(uname -s)" in\n'
        f'  Darwin) DIRECTORY="$HOME/Library/Application Support/{app_id}/installation" ;;\n'
        "  *)\n"
        '    case "${XDG_DATA_HOME-}" in\n'
        "      /*) DATA_HOME=$XDG_DATA_HOME ;;\n"
        '      *) DATA_HOME="$HOME/.local/share" ;;\n'
        "    esac\n"
        f'    DIRECTORY="$DATA_HOME/{app_id}/installation" ;;\n'
        "esac\n"
        f'exec "$DIRECTORY/{saved}" "$@"\n'
    )
    windows = (
        "@echo off\r\nsetlocal\r\n"
        'if not defined LOCALAPPDATA set "LOCALAPPDATA=%USERPROFILE%\\AppData\\Local"\r\n'
        f'set "DIRECTORY=%LOCALAPPDATA%\\{app_id}\\installation"\r\n'
        f'call "%DIRECTORY%\\{batch_saved}" %*\r\n'
        "exit /b %ERRORLEVEL%\r\n"
    )
    return (
        _artifact(spec, f"{command}.sh", shell.encode(), executable=True),
        _artifact(spec, f"{command}.cmd", windows.encode()),
    )


def render_launcher(spec: DistributionSpec) -> tuple[Artifact, ...]:
    """Render root launch wrappers that dispatch to the adjacent saved launcher."""
    return _wrappers(spec, command="app-launch", entry="launch")


def render_uninstaller(spec: DistributionSpec) -> tuple[Artifact, ...]:
    """Render root removal wrappers that dispatch to the adjacent saved uninstaller."""
    return _wrappers(spec, command="app-uninstall", entry="uninstall")


def generate_artifacts(
    spec: DistributionSpec, payload: PayloadTree
) -> tuple[Artifact, ...]:
    """Compose all tracked installer, saved-support and root wrapper outputs.

    :param spec: Author-selected metadata, source and capabilities.
    :param payload: Explicit application composition tree.
    :return: Complete artifact set with collision-checked destinations.
    """
    main = build_main_installer(spec, payload)
    support = render_saved_support(spec, payload)
    artifacts = (
        *render_bootstraps(spec),
        main,
        *support,
        *render_launcher(spec),
        *render_uninstaller(spec),
    )
    destinations = [artifact.destination for artifact in artifacts]
    if len(destinations) != len(set(destinations)):
        raise ValueError(
            "Generated artifact composition contains duplicate destinations."
        )
    return tuple(artifacts)


def render_saved_support(
    spec: DistributionSpec, payload: PayloadTree
) -> tuple[Artifact, ...]:
    """Render grouped checkout support outputs and installable saved controllers."""
    from apprc.distribution.standalone import inspection_archive

    base = f"{spec.metadata.distribution_path}/artifacts"
    inspector = (
        _environment()
        .get_template("inspection.py.jinja")
        .render(
            archive=base64.b64encode(inspection_archive()).decode("ascii"),
        )
        .encode()
    )
    command = (
        spec.metadata.launcher_command or spec.metadata.identity.commands[0]
    )
    return (
        _artifact(
            spec,
            f"{base}/installer/repair-installer.py",
            standalone_script(
                spec, payload, entry=payload.entry_module, public_entry=False
            ),
        ),
        _artifact(
            spec,
            f"{base}/installer/app-uninstall.py",
            standalone_script(
                spec, payload, entry=payload.uninstall_entry_module
            ),
        ),
        _artifact(
            spec,
            f"{base}/uninstaller/controller.py",
            standalone_script(
                spec, payload, entry="apprc.distribution.runtime.removal"
            ),
        ),
        _artifact(spec, f"{base}/uninstaller/inspection.py", inspector),
        _artifact(
            spec, f"{base}/uninstaller/final-worker.py", _stdlib_worker()
        ),
        _artifact(
            spec,
            f"{base}/management/management.py",
            files("apprc.distribution")
            .joinpath("runtime", "saved_management.py")
            .read_bytes(),
        ),
        _artifact(
            spec,
            f"{base}/management/management.json",
            (
                json.dumps(
                    {
                        "app_id": spec.metadata.identity.app_id,
                        "command": command,
                        "base_python": None,
                    },
                    sort_keys=True,
                )
                + "\n"
            ).encode(),
        ),
        _artifact(
            spec,
            f"{base}/launcher/launch.sh",
            _saved_frontend("sh", "launch", spec),
            executable=True,
        ),
        _artifact(
            spec,
            f"{base}/launcher/launch.ps1",
            _saved_frontend("ps1", "launch", spec),
        ),
        _artifact(
            spec,
            f"{base}/launcher/launch.cmd",
            _saved_frontend("cmd", "launch", spec),
        ),
        _artifact(
            spec,
            f"{base}/uninstaller/uninstall.sh",
            _saved_frontend("sh", "uninstall", spec),
            executable=True,
        ),
        _artifact(
            spec,
            f"{base}/uninstaller/uninstall.ps1",
            _saved_frontend("ps1", "uninstall", spec),
        ),
        _artifact(
            spec,
            f"{base}/uninstaller/uninstall.cmd",
            _saved_frontend("cmd", "uninstall", spec),
        ),
    )


def install_support_files(
    spec: DistributionSpec,
    payload: PayloadTree,
) -> dict[PurePosixPath, bytes]:
    """Flatten grouped generated support to exact installation-relative paths."""
    root = (
        PurePosixPath(spec.metadata.distribution_path.as_posix()) / "artifacts"
    )
    artifacts = render_saved_support(spec, payload)
    result = {}
    for artifact in artifacts:
        relative = artifact.destination.relative_to(root)
        if relative.parts[0] in {
            "installer",
            "launcher",
            "uninstaller",
            "management",
        }:
            relative = PurePosixPath(*relative.parts[1:])
        result[relative] = artifact.content
    if len(result) != len(artifacts):
        raise ValueError(
            "Saved support artifacts contain duplicate install paths."
        )
    return result


def _saved_frontend(
    platform: str, action: str, spec: DistributionSpec
) -> bytes:
    """Create a native frontend with install-time command/interpreter bindings."""
    command = (
        spec.metadata.launcher_command or spec.metadata.identity.commands[0]
    )
    if action == "launch":
        if platform == "sh":
            return (
                f"#!/bin/sh\n# APPRC-LAUNCH-COMMAND: {json.dumps(command)}\n"
                'set -eu\nexec __APPRC_COMMAND_PATH__ "$@"\n'
            ).encode()
        if platform == "ps1":
            return (
                f"# APPRC-LAUNCH-COMMAND: {json.dumps(command)}\n"
                "& __APPRC_COMMAND_PATH__ @args\nexit $LASTEXITCODE\n"
            ).encode()
        return (
            f"@echo off\r\nrem APPRC-LAUNCH-COMMAND: {json.dumps(command)}\r\n"
            "__APPRC_COMMAND_PATH__ %*\r\nexit /b %ERRORLEVEL%\r\n"
        ).encode()
    if platform == "sh":
        return (
            "#!/bin/sh\nset -eu\n"
            'exec __APPRC_BASE_PYTHON__ "$(dirname -- "$0")/management.py" uninstall '
            '--directory "$(dirname -- "$0")" "$@"\n'
        ).encode()
    if platform == "ps1":
        return (
            "$ErrorActionPreference = 'Stop'\n"
            "& __APPRC_BASE_PYTHON__ (Join-Path $PSScriptRoot 'management.py') uninstall "
            "--directory $PSScriptRoot @args\nexit $LASTEXITCODE\n"
        ).encode()
    return (
        '@echo off\r\n__APPRC_BASE_PYTHON__ "%~dp0management.py" uninstall '
        '--directory "%~dp0" %*\r\nexit /b %ERRORLEVEL%\r\n'
    ).encode()


def _stdlib_worker() -> bytes:
    """Serialize the stdlib-only post-retirement empty-namespace finalizer."""
    return (
        files("apprc.distribution")
        .joinpath("runtime", "namespace_finalizer.py")
        .read_bytes()
    )


def build_main_installer(
    spec: DistributionSpec, payload: PayloadTree
) -> Artifact:
    """Build script or explicit zipapp from exactly one loader/runtime closure.

    :param spec: Portable generation and payload-format selection.
    :param payload: Repository-owned ordinary-Python composition.
    :return: Main installer output; zipapp dependencies are emitted separately.
    """
    content = standalone_script(spec, payload, entry=payload.entry_module)
    filename = "main-installer.py"
    if spec.payload_format == "zipapp":
        buffer = io.BytesIO()
        with ZipFile(
            buffer, "w", compression=ZIP_DEFLATED, compresslevel=9
        ) as archive:
            info = ZipInfo("__main__.py", date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            info.compress_type = ZIP_DEFLATED
            archive.writestr(info, content)
        content = buffer.getvalue()
        filename = "main-installer.pyz"
    return Artifact(
        spec.metadata.distribution_path / "artifacts" / "installer" / filename,
        content,
        True,
        spec.metadata.project_root,
    )
